// IngressServiceName is the compose service Hull injects to front a cluster in
// ingress: delegate mode.
const IngressServiceName = "hull-ingress"

// ingressOverlayFile / ingressCaddyFile are written into the compose root.
const (
	ingressOverlayFile = "compose.hull.yaml"
	ingressCaddyFile   = "compose.hull.caddy"
)

// IngressArtifacts is the generated pair for a cluster's ingress container: a
// compose overlay (added as an extra -f) and the Caddy config it mounts.
type IngressArtifacts struct {
	Overlay   []byte
	Caddyfile string
	BindIP    string
	Networks  []string
	Hosts     []string
}

// ClusterIngress builds the ingress-container artifacts for a cluster: a
// reverse proxy attached to every cluster network (so it can reach internal-only
// services by name), publishing 80/443 on a per-cluster loopback IP, with a
// network alias per routed hostname so in-network server-side calls resolve to
// it. It does not touch disk; callers preview or write the result.
func (e *Engine) ClusterIngress(p *state.Project, replaceProxy string) (*IngressArtifacts, error) {
	m := p.Manifest
	if m == nil || m.Type != manifest.TypeCluster {
		return nil, fmt.Errorf("%s is not a cluster", p.Name)
	}
	composeDir := filepath.Join(p.Dir, m.ComposeRoot)
	networks := readClusterNetworks(composeDir, m.ComposeFiles)
	if len(networks) == 0 {
		return nil, fmt.Errorf("cluster %s declares no networks for the ingress to join (delegate ingress needs the compose to define networks)", m.Name)
	}
	if replaceProxy != "" {
		if svcs := composeServiceNames(composeDir, m.ComposeFiles); svcs != nil && !svcs[replaceProxy] {
			return nil, fmt.Errorf("service %q (to replace) is not in %s's compose (services: %s)", replaceProxy, m.Name, sortedKeys(svcs))
		}
	}
	suffix := m.ClusterSuffix(e.cfg().TLD)
	hosts := clusterHosts(m, suffix)
	if len(hosts) == 0 {
		return nil, fmt.Errorf("cluster %s has no served routes; assign one with `hull cluster route add`", m.Name)
	}
	bindIP, err := e.ingressIP(p)
	if err != nil {
		return nil, err
	}
	hasLoopback := e.HasLoopback
	if hasLoopback == nil {
		hasLoopback = platform.LoopbackPresent
	}
	if !hasLoopback(bindIP) {
		return nil, fmt.Errorf("the ingress for %s needs its own loopback address %s, which this machine does not have; add it with `sudo ifconfig lo0 alias %s up` (it lasts until reboot), or use `ingress: hull`", m.Name, bindIP, bindIP)
	}

	overlay, err := ingressOverlay(m.Name, networks, hosts, bindIP, replaceProxy)
	if err != nil {
		return nil, err
	}
	return &IngressArtifacts{
		Overlay:   overlay,
		Caddyfile: ingressCaddyfile(m, suffix),
		BindIP:    bindIP,
		Networks:  networks,
		Hosts:     hosts,
	}, nil
}

// WriteClusterIngress writes the overlay + Caddyfile into the compose root, so
// the cluster can be started with the extra -f file.
func (e *Engine) WriteClusterIngress(p *state.Project, art *IngressArtifacts) error {
	composeDir := filepath.Join(p.Dir, p.Manifest.ComposeRoot)
	if err := safefile.Write(filepath.Join(composeDir, ingressOverlayFile), art.Overlay, 0o644); err != nil {
		return err
	}
	return safefile.Write(filepath.Join(composeDir, ingressCaddyFile), []byte(art.Caddyfile), 0o644)
}

// clusterHosts is the sorted, de-duplicated set of served hostnames.
func clusterHosts(m *manifest.Manifest, suffix string) []string {
	seen := map[string]bool{}
	var hosts []string
	for _, key := range m.RouteKeys() {
		rt := m.Routes[key]
		if !rt.Served() {
			continue
		}
		for _, h := range rt.Hosts(suffix) {
			if !seen[h] {
				seen[h] = true
				hosts = append(hosts, h)
			}
		}
	}
	sort.Strings(hosts)
	return hosts
}

// ingressCaddyfile renders the Caddy config the ingress container serves: one
// vhost per routed hostname, reverse-proxying to the compose service by name
// (reachable because the ingress shares the cluster networks, so internal-only
// services work too). TLS is Caddy's internal CA inside the container.
func ingressCaddyfile(m *manifest.Manifest, suffix string) string {
	var b strings.Builder
	b.WriteString("# Generated by Hull , do not edit (regenerated on `hull up`).\n")
	b.WriteString("{\n\tauto_https disable_redirects\n}\n\n")
	for _, key := range m.RouteKeys() {
		rt := m.Routes[key]
		if !rt.Served() {
			continue
		}
		for _, host := range rt.Hosts(suffix) {
			fmt.Fprintf(&b, "%s {\n\ttls internal\n\treverse_proxy %s:%d {\n\t\theader_up X-Forwarded-Proto https\n\t}\n}\n\n", host, rt.Service, rt.Port)
		}
	}
	return b.String()
}

// ingressOverlay renders the compose.hull.yaml overlay that adds the ingress
// service to a cluster. The cluster's networks are declared in its base compose,
// so the overlay only references them (compose merges the two -f files); each is
// given a per-hostname alias so in-network calls to the public names resolve to
// the ingress.
func ingressOverlay(name string, networks, hosts []string, bindIP, replaceProxy string) ([]byte, error) {
	nets := map[string]any{}
	for _, n := range networks {
		nets[n] = map[string]any{"aliases": append([]string(nil), hosts...)}
	}
	svc := map[string]any{
		"image":          "caddy:2.10-alpine",
		"container_name": "hull-ingress-" + name,
		"restart":        "unless-stopped",
		"networks":       nets,
		"ports": []string{
			bindIP + ":80:80",
			bindIP + ":443:443",
		},
		"volumes": []string{
			"./" + ingressCaddyFile + ":/etc/caddy/Caddyfile:ro",
		},
	}
	services := map[string]any{IngressServiceName: svc}
	// Promote: scale the cluster's own proxy to zero so Hull's ingress takes
	// over cleanly. Reversible , delete the overlay to restore it.
	if replaceProxy != "" {
		services[replaceProxy] = map[string]any{"deploy": map[string]any{"replicas": 0}}
	}
	doc := map[string]any{
		"services": services,
	}
	var buf strings.Builder
	buf.WriteString("# Generated by Hull , the cluster ingress overlay. Do not edit.\n")
	buf.WriteString("# Run with the base compose: docker compose -f <base> -f " + ingressOverlayFile + " up -d\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	_ = enc.Close()
	return []byte(buf.String()), nil
}

// ingressIP picks the 127.0.0.x a cluster's ingress binds: the address its
// written overlay already uses, so it stays put, else the first free one from
// a hash of its name, skipping 127.0.0.1, Hull's own router address and every
// other cluster's ingress, so two clusters never fight over one address.
func (e *Engine) ingressIP(p *state.Project) (string, error) {
	if ip := overlayIP(filepath.Join(p.Dir, p.Manifest.ComposeRoot)); ip != "" {
		return ip, nil
	}
	taken := map[string]bool{"127.0.0.1": true, e.cfg().Router.Loopback: true}
	projects, _ := state.Scan(e.cfg().Roots, e.cfg().Projects...)
	for i := range projects {
		q := &projects[i]
		if isCluster(q) && q.Dir != p.Dir {
			if ip := overlayIP(filepath.Join(q.Dir, q.Manifest.ComposeRoot)); ip != "" {
				taken[ip] = true
			}
		}
	}
	h := fnv.New32a()
	_, _ = h.Write([]byte(p.Manifest.Name))
	start := int(h.Sum32() % 252) // octets 2..253
	for i := 0; i < 252; i++ {
		ip := fmt.Sprintf("127.0.0.%d", (start+i)%252+2)
		if !taken[ip] {
			return ip, nil
		}
	}
	return "", fmt.Errorf("no free 127.0.0.x address left for %s's ingress", p.Manifest.Name)
}

var overlayIPRE = regexp.MustCompile(`(127\.0\.0\.\d+):80:80`)

// overlayIP is the address a written ingress overlay in composeDir binds, or "".
func overlayIP(composeDir string) string {
	data, err := os.ReadFile(filepath.Join(composeDir, ingressOverlayFile))
	if err != nil {
		return ""
	}
	if m := overlayIPRE.FindSubmatch(data); m != nil {
		return string(m[1])
	}
	return ""
}

// readClusterNetworks returns the network keys declared across a cluster's
// compose files (best-effort; nil when none declare any).
func readClusterNetworks(composeDir string, files []string) []string {
	seen := map[string]bool{}
	for _, data := range composeDocs(composeDir, files) {
		var doc struct {
			Networks map[string]yaml.Node `yaml:"networks"`
		}
		if yaml.Unmarshal(data, &doc) == nil {
			for n := range doc.Networks {
				seen[n] = true
			}
		}
	}
	if len(seen) == 0 {
		return nil
	}
	names := make([]string, 0, len(seen))
	for n := range seen {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}
